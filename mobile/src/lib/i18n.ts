const TABLES: Record<string, Strings> = {
  'en-IN': en,
  'hi-IN': hi,
  'mr-IN': mr,
  'bn-IN': bn,
  'ta-IN': ta,
  'te-IN': te,
  'kn-IN': kn,
  'ml-IN': ml,
  'gu-IN': gu,
  'pa-IN': pa,
  'od-IN': od,
};

export function translate(
  language: string,
  key: StringKey,
  vars?: Record<string, string | number>,
): string {
  let text = TABLES[language]?.[key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
  return text;
}

/** `const t = useT(); t('home.headline')` in the user's chosen language. */
export function useT() {
  const { profile } = useApp();
  const language = profile?.language ?? 'en-IN';
  return (key: StringKey, vars?: Record<string, string | number>) => translate(language, key, vars);
}
